def propose_bucket(domain: str, ntags):
    """يرجع معرف العقدة المقترحة لفرعيات ذرة بلا نظير في الشجرة."""
    root = DOMAIN_ROOT.get(domain, "p.misc")
    tree = PROPOSED_TREES.get(root)
    if not tree:
        return root
    joined = " ".join(ntags)
    for bid, _t, kw in tree["buckets"]:
        if kw and re.search(kw, joined):
            return bid
    # آخر دلو في كل شجرة هو misc
    return tree["buckets"][-1][0] if tree["buckets"] else root


