def load_nodes():
    m = json.load(open(FIHRIS_MAPPING, encoding="utf-8"))
    nodes = {}

    def walk(ns, depth, parent):
        for n in ns:
            nodes[n["id"]] = {"t": n["t"], "depth": depth, "parent": parent}
            walk(n.get("ch", []), depth + 1, n["id"])

    walk(m["tree"], 0, None)
    nodes["x.appendix"] = {"t": m["appendix"]["t"], "depth": 0, "parent": None}
    return nodes


def title_match(title_norm: str, domain: str):
    """أول قاعدة عنوان تُصيب (مرتبة: أولاً = أعلى ثقة)."""
    for pat, domains, node, conf in TITLE_RULES:
        if domain in domains and re.search(pat, title_norm):
            return node, conf, pat
    return None


def map_atom(series: str, e):
    """يرجع (node|None, via, conf, matched, proposed_bucket|None)."""
    dom = atom_domain(series, (e.get("tags") or ["أخرى"])[0])
    key = f"{series}|{e['id']}"
    if key in MANUAL:
        node, conf, note = MANUAL[key]
        return node, "manual", conf, note, None
    tags = e.get("tags", [])
    best = None
    for raw in tags[1:]:
        nt = norm(raw)
        if not nt or is_non_topical(nt):
            continue
        hit = ALIAS.get((dom, nt)) or ALIAS.get(("*", nt))
        if hit and (best is None or hit[1] > best[1]):
            best = (hit[0], hit[1], raw)
    if best:
        return best[0], "tag-normalized", best[1], best[2], None
    tm = title_match(norm(e.get("title", "")), dom)
    if tm:
        node, conf, pat = tm
        return node, "title-match", conf, f"pat:{pat}", None
    topical = [t for t in (norm(x) for x in tags[1:]) if t and not is_non_topical(t)]
    if not topical:
        # لا فرعية موضوعية أصلاً (افتتاحية/خاتمة/مرساة متن) — لا تُقترح عقدة.
        return None, "unmatched", 0.0, "no-topical-tags", None
    # نطاق الاقتراح: «أخرى»/«أصول» يرثان علم السلسلة، وإلا علم الوسم الأول —
    # فذرة نحوية عارضة داخل شرح أم البراهين تقترح في p.nahw لا في p.kalam.
    first = tags[0] if tags else "أخرى"
    dom_prop = dom
    if first in ("أخرى", "أصول"):
        num = series.split("_")[0]
        if num in SERIES_DOMAIN:
            dom_prop = SERIES_DOMAIN[num]
    return None, "unmatched", 0.0, ",".join(topical), propose_bucket(dom_prop, topical)


# ---------------------------------------------------------------------------
def main():
    nodes = load_nodes()
    links = {}
    per_node = defaultdict(list)          # node -> [(key, series, conf, via)]
    proposed_tags = defaultdict(Counter)  # bucket -> Counter(tag)
    proposed_atoms = defaultdict(list)    # bucket -> [key]
    sci_stats = Counter()
    dom_stats = Counter()
    via_stats = Counter()

    for idx in sorted(ATOMS_DIR.glob("*/index.json")):
        d = json.load(open(idx, encoding="utf-8"))
        series = d["series"]
        for e in d["entries"]:
            key = f"{series}|{e['id']}"
            node, via, conf, matched, proposed = map_atom(series, e)
            first = (e.get("tags") or ["?"])[0]
            sci_stats[first] += 1
            dom = atom_domain(series, first)
            dom_stats[dom] += 1
            via_stats[via] += 1
            links[key] = {
                "atom": e["id"], "series": series, "sheikh": d.get("sheikh"),
                "title": e["title"], "tags": e.get("tags", []),
                "domain": dom, "node": node, "via": via,
                "confidence": conf, "matched": matched,
            }
            if node:
                links[key]["proposed"] = None
                per_node[node].append((key, series, conf, via))
            else:
                links[key]["proposed"] = proposed
                if proposed:
                    proposed_atoms[proposed].append(key)
                    for t in (norm(x) for x in e.get("tags", [])[1:]):
                        if t and not is_non_topical(t):
                            proposed_tags[proposed][t] += 1

    n_atoms = len(links)
    n_linked = sum(1 for v in links.values() if v["node"])
    covered = {n for n in nodes if per_node.get(n)}
    orphan_nodes = [n for n in nodes if not per_node.get(n)]

    # ---------- atom_links.json ----------
    links_json = {
        "_doc": "ذرة → عقدة فهرس. node=null = لا نظير موثوق؛ انظر proposed (بيت مقترح في PROPOSED_NODES.md).",
        "_via": {
            "manual": "ربط بشري موثّق (SAMPLE.md)",
            "tag-normalized": "فرعية حرة طابقت اسماً مستعاراً للعقدة ضمن نطاق علمها",
            "title-match": "عبارة مميزة في عنوان الذرة ضمن نطاق مسموح",
            "unmatched": "لا نظير — مقترحة كعقد جديدة، لا محشورة قسراً",
        },
        "_confidence": "0–1؛ <0.6 = تغطية جزئية أو استدلال ضعيف، لا تُقدَّم للمستخدم كربط مؤكد.",
        "stats": {
            "atoms_total": n_atoms, "atoms_linked": n_linked,
            "atoms_unlinked": n_atoms - n_linked,
            "nodes_total": len(nodes), "nodes_covered": len(covered),
            "nodes_orphan": len(orphan_nodes),
            "coverage_nodes_pct": round(100 * len(covered) / len(nodes), 1),
            "coverage_atoms_pct": round(100 * n_linked / n_atoms, 1),
            "by_via": dict(via_stats), "by_domain": dict(dom_stats),
            "by_first_tag": dict(sci_stats),
        },
        "links": links,
    }
    OUT_DATA.mkdir(parents=True, exist_ok=True)
    with open(OUT_LINKS, "w", encoding="utf-8") as f:
        json.dump(links_json, f, ensure_ascii=False, indent=1)

    # ---------- coverage.md ----------
    def node_line(nid):
        rows = per_node.get(nid, [])
        n = len(rows)
        confs = [c for _, _, c, _ in rows]
        series = sorted({s for _, s, _, _ in rows})
        return n, confs, series

    children = defaultdict(list)
    for nid, nd in nodes.items():
        children[nd["parent"]].append(nid)

    L = []
    L.append("# تغطية عقد الفهرس بذرات الدروس\n")
    L.append("المصدر: `tools/map_atoms.py` (خرج آليّ — أعِد توليده بعد تحرير القاموس).")
    L.append("شجرة الفهرس الحالية علمها **أصول الفقه** فقط (88 عقدة + ملحق)؛")
    L.append("بنك الذرات لا يحوي سلسلة أصول فقه مستقلة — التغطية تأتي من ذرات")
    L.append("متناثرة في سلاسل العقيدة والمنطق والمصطلح والفقه.\n")
    L.append("## الأرقام\n")
    L.append(f"- الذرات الكلية: **{n_atoms}** — المربوطة: **{n_linked}**"
             f" ({round(100*n_linked/n_atoms,1)}%)")
    L.append(f"- العقد الكلية: **{len(nodes)}** — المغطاة بذرة+ : **{len(covered)}**"
             f" ({round(100*len(covered)/len(nodes),1)}%) — اليتيمة: **{len(orphan_nodes)}**")
    L.append(f"- بطرق الربط: {dict(via_stats)}")
    L.append(f"- بنطاقات الذرات: {dict(dom_stats)}\n")
    L.append("## جدول العقد\n")
    L.append("| العقدة | العنوان | ذرات | ثقة قصوى/وسطى | سلاسل |")
    L.append("|---|---|---|---|---|")
    for nid, nd in nodes.items():
        n, confs, series = node_line(nid)
        if n:
            import statistics
            med = statistics.median(confs)
            L.append(f"| `{nid}` | {nd['t']} | {n} | "
                     f"{max(confs):.2f}/{med:.2f} | {len(series)}: {'، '.join(s[:22] for s in series[:4])}"
                     f"{'…' if len(series) > 4 else ''} |")
        else:
            L.append(f"| `{nid}` | {nd['t']} | **0** | — | — |")
    L.append("\n## العقد اليتيمة (فجوات المحتوى الحقيقية)\n")
    L.append("لا تغطيها أي ذرة درس — مرشحة للإنتاج لا للحشر القسري:\n")
    for nid in orphan_nodes:
        L.append(f"- `{nid}` — {nodes[nid]['t']}")
    L.append("\n## ملاحظات الثقة\n")
    L.append("- conf ≥0.8 تطابق موضوعي شبه مؤكد؛ 0.6–0.8 تغطية حقيقية بفرق اصطلاح؛")
    L.append("  <0.6 إشارة موضوعية فقط — راجع النص قبل اعتمادها.")
    L.append("- «القياس» المنطقي و«التقليد» الكلامي و«الكلام» (صفة) و«استثناء الإيمان»")
    L.append("  مستبعدة عمداً بقاعدة النطاق — انظر قاموس ALIAS في الأداة.")
    with open(OUT_COVERAGE, "w", encoding="utf-8") as f:
        f.write("\n".join(L))

    # ---------- PROPOSED_NODES.md ----------
    P = []
    P.append("# عقد مقترحة للشجرة — الفرعيات اليتيمة\n")
    P.append("الفرعيات الحرة التي لا نظير موثوق لها في عقد الفهرس الـ88، مجمّعة تحت")
    P.append("سقالات علوم مقترحة `p.*`. هذه **اقتراح توسعة** لا جزء من الشجرة؛")
    P.append("ترتيب الذرات تحتها في `data/atom_links.json` (حقل `proposed`).\n")
    P.append("## أعلى الفرعيات اليتيمة تكراراً لكل سقالة\n")
    for root, tree in PROPOSED_TREES.items():
        total_atoms = len(proposed_atoms.get(root, []))
        bucket_atoms = {b[0]: len(proposed_atoms.get(b[0], [])) for b in tree["buckets"]}
        root_atoms = bucket_atoms.pop(root, 0) + total_atoms
        n_root_atoms = sum(bucket_atoms.values()) + root_atoms
        if not n_root_atoms:
            continue
        P.append(f"### `{root}` — {tree['t']} ({n_root_atoms} ذرة)\n")
        for bid, bt, kw in tree["buckets"]:
            atoms = proposed_atoms.get(bid, [])
            tags = proposed_tags.get(bid, Counter())
            if not atoms and not tags:
                continue
            P.append(f"#### `{bid}` — {bt} — {len(atoms)} ذرة، {len(tags)} فرعية\n")
            if tags:
                show = "، ".join(f"{t} ({c})" for t, c in tags.most_common(25))
                P.append(f"فرعيات: {show}")
                if len(tags) > 25:
                    P.append(f"… و{len(tags)-25} فرعية أخرى في `atom_links.json`")
            P.append("")
    with open(OUT_PROPOSED, "w", encoding="utf-8") as f:
        f.write("\n".join(P))

    print(json.dumps({
        "atoms": n_atoms, "linked": n_linked,
        "nodes": len(nodes), "covered": len(covered),
        "cov_nodes_pct": round(100 * len(covered) / len(nodes), 1),
        "cov_atoms_pct": round(100 * n_linked / n_atoms, 1),
        "by_via": dict(via_stats),
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
