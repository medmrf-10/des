def anchor_positions(idx, anchor):
    """كل مواضع المرساة (بدءاً) في النص — توكنات مجرّدة، وتخطّي
    توكنات الأرقام (إحالات الهوامش «(¬٢)») كما في المحرك."""
    aw = [_stem(t) for t in _norm(anchor).split()]
    out = []
    for i in idx._posting().get(aw[0], []):
        j, k = i, 0
        while k < len(aw) and j < len(idx.stoks):
            if idx.stoks[j].isdigit():
                j += 1
                continue
            if idx.stoks[j] != aw[k]:
                break
            j += 1
            k += 1
        if k == len(aw):
            out.append(idx.cs[i])
    return out


def verdict(idx, res, positions):
    """hit/broad/miss/none + سبب عربي."""
    if not res.get('found'):
        return 'miss', 'لم يجد المحرك مرشحاً فوق العتبة'
    if not positions:
        return 'miss', 'المرساة غير موجودة في النص (خطأ عينة)'
    inside = [p for p in positions if res['cs'] <= p < res['ce']]
    if not inside:
        return 'miss', f"المقطع المُعاد في «{res['sec'] or '؟'}» لا يحوي المرساة"
    # مرشح أدقّ داخل المقطع يحوي المرساة؟ → إصابة فضفاضة
    for c in idx.cands:
        if res['cs'] < c['cs'] and c['ce'] <= res['ce'] \
                and c['cs'] != res['cs'] \
                and any(c['cs'] <= p < c['ce'] for p in inside):
            return 'broad', f"أصاب المنطقة؛ الفقرة الأدق تبدأ {c['cs']}"
    return 'hit', ''


