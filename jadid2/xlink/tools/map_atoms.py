# 1) التطبيع — norm()
# ---------------------------------------------------------------------------
# الهدف: توحيد صور الكتابة الشائعة في الفرعيات الحرة دون إسقاط معنى.
#   - إزالة التشكيل والتطويل والأنماط الزخرفية
#   - توحيد الألف (أإآٱ→ا) والياء/الألف المقصورة (ى→ي) والتاء المربوطة (ة→ه)
#   - إزالة كل ما ليس حرفاً/رقماً (علامات الاقتباس في «قوله ＂…＂» وغيرها)
#   - ضغط الفراغات
# التاء/الهاء والياء/المقصورة موحَّدة لأن الموسِّمين كتبوها عشوائياً
# («الدباجه»/«الدباجة»)؛ التوحيد أسلم من فقدان التطابق، والجدول موثّق أدناه.
_DIACRITICS = re.compile(r"[ً-ٰٟـۖ-ۭﭐ-﮿＂＂«»\"'!؟?.,،؛:()\[\]{}<>|/\\\-ـ—_]+")


def norm(s: str) -> str:
    s = unicodedata.normalize("NFKC", s)
    s = _DIACRITICS.sub(" ", s)
    s = re.sub("[أإآٱ]", "ا", s)
    s = s.replace("ى", "ي").replace("ة", "ه")
    s = re.sub(r"\s+", " ", s).strip()
    return s


